const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
const html=fs.readFileSync('web/index.html','utf8');
assert.ok(!html.includes('非人工录入先校验后放行'));
assert.ok(html.includes('<option value="accounted">已入人员与账号</option>'));
assert.ok(html.includes('<option value="account_pending">已确认待补录</option>'));
assert.ok(html.includes('<option value="excluded">排除名单</option>'));
assert.ok(html.includes('有账号 ID 时排除对所有现有及新增来源群生效'));
assert.ok(html.includes('function renderPublisherExclusions'));
const start=html.indexOf('function publisherAccountState');
const end=html.indexOf('function openHealthReview',start);
assert.ok(start>=0 && end>start,'publisher management functions exist');
const context={S:{auth:{role:'admin'}},console};
vm.createContext(context);
vm.runInContext(html.slice(start,end),context);
const base={identity_key:'open:oid1',sender_open_id:'oid1',sender_id:'sid1',identity_conflict:false,
  assessment:{status:'insufficient',basis:'insufficient'}};
const pending=context.publisherActions({...base,account_library:{registered:false}},'c1');
assert.ok(pending.includes('确认航管'));
assert.ok(pending.includes('confirmPublisherAccount'));
assert.ok(!pending.includes('openPublisherDecision(&quot;c1&quot;,&quot;confirm&quot;)'));
const managed=context.publisherActions({...base,assessment:{status:'publisher',basis:'user_confirmed_account'},account_library:{registered:true}},'c1');
assert.ok(!managed.includes('确认航管'));
assert.ok(managed.includes('改为排除'));
assert.ok(managed.includes('excludePublisherAccount'));
assert.ok(!managed.includes('openPublisherDecision(&quot;c1&quot;,&quot;exclude&quot;)'));
const backfill=context.publisherActions({...base,assessment:{status:'publisher',basis:'user_confirmed_account'},account_library:{registered:false}},'c1');
assert.ok(backfill.includes('补录人员与账号'));
assert.ok(!backfill.includes('确认航管'));
assert.ok(backfill.includes('confirmPublisherAccount'));
const nameOnly=context.publisherActions({...base,identity_key:'name:航管甲',sender_open_id:'',sender_id:''},'c1');
assert.ok(nameOnly.includes('排除当前群'));
assert.ok(nameOnly.includes('excludePublisherAccount'));
assert.ok(!nameOnly.includes('确认航管'));
assert.ok(html.includes('按姓名仅对当前来源群生效'));
assert.match(html,/async function excludePublisherAccount\(id,button\)/);
assert.match(html,/async function confirmPublisherAccount\(id,button\)/);
assert.ok(html.includes("publisherData?.exclusions.find(c=>c.candidate_id===id)"));
console.log('PASS: publisher confirmation actions follow stable identity, roster state, and account-library state');
